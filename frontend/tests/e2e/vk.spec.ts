import { test, expect } from '@playwright/test';
import { authenticate } from './auth';

test('VK channel accepts settings, rotates a hidden token and sends through the local TLS fixture', async ({ page, baseURL }) => {
  test.skip(!process.env.E2E_DELIVERY_FIXTURE, 'Requires the isolated local delivery fixture');
  await authenticate(page, baseURL!);
  const name = `ВКонтакте ${Date.now()}`;
  await page.goto('/#templates');
  await page.getByRole('button', { name: 'Создать шаблон', exact: true }).click();
  await page.getByLabel('Название', { exact: true }).fill(name);
  await page.getByLabel('Тип канала', { exact: true }).selectOption('VK');
  await page.getByLabel('Текст уведомления', { exact: true }).fill('{{ event.body }}');
  await page.getByRole('button', { name: 'Сохранить', exact: true }).click();
  await expect(page.getByRole('status')).toHaveText('Шаблон сохранён');
  await page.goto('/#channels');
  await page.getByRole('button', { name: 'Создать канал', exact: true }).click();
  await page.getByLabel('Тип канала', { exact: true }).selectOption('VK');
  await page.getByLabel('Название', { exact: true }).fill(name);
  await page.getByLabel('Идентификатор сообщества', { exact: true }).fill('123');
  await page.getByLabel('Идентификатор получателя', { exact: true }).fill('2000000001');
  await page.getByLabel('Токен доступа', { exact: true }).fill('vk-local-test-first');
  await page.getByLabel('Шаблон', { exact: true }).selectOption({ label: name });
  await page.getByRole('button', { name: 'Сохранить', exact: true }).click();
  await expect(page.getByRole('status')).toHaveText('Настройки сохранены');
  await page.getByRole('button', { name: `Изменить «${name}»`, exact: true }).click();
  await expect(page.getByLabel('Токен доступа', { exact: true })).toHaveValue('');
  await page.getByLabel('Токен доступа', { exact: true }).fill('vk-local-test-second');
  await page.getByRole('button', { name: 'Сохранить', exact: true }).click();
  await expect(page.getByRole('status')).toHaveText('Настройки сохранены');
  const row = page.getByRole('row').filter({ hasText: name });
  await row.getByRole('button', { name: /Проверить подключение/ }).click();
  await expect(page.getByRole('status')).toContainText('Токен сообщества и право работы с сообщениями проверены');
  await row.getByRole('button', { name: 'Отправить тестовое уведомление', exact: true }).click();
  const form = page.getByRole('form', { name: 'Тестовое уведомление', exact: true });
  await form.getByLabel('Текст события', { exact: true }).fill('Проверка ВКонтакте через локальный имитатор');
  await form.getByRole('button', { name: 'Отправить тестовое уведомление', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Уведомление', exact: true })).toBeVisible();
  await expect(page.locator('dd').filter({ hasText: /^Отправлено$/ })).toBeVisible({ timeout: 20000 });
  const channels = await (await page.request.get('/api/v1/channels')).json();
  expect(JSON.stringify(channels)).not.toMatch(/vk-local-test-first|vk-local-test-second/);
  expect(channels.items.find((v: { name: string }) => v.name === name).secret_version).toBe(2);
});
